print("É um número:", varia.isnumeric())
print("É alfabético?", varia.isalpha())
print("É alfanúmerico?", varia.isalnum())
print("Está em maiúsculo?",varia.isupper())
print("Está em minúsculo",varia.islower())
print("Está capitalizado",varia.istitle())

